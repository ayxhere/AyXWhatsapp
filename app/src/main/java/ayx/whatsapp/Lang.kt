import android.content.Context
import androidx.compose.runtime.mutableStateOf

/**
 * App language (i18n) store — Phase 2: English + Hindi + Bangla + Indonesian + Malaysian + Russian.
 * All UI strings live here keyed by stable keys. [Lang.s] never
 * crashes and never returns blank: Hindi if selected and present,
 * else English, else the key itself.
 *
 * Changing [current] triggers recomposition app-wide (mutableState),
 * so language switches apply instantly with no Activity restart.
 */
object Lang {
    const val EN = "en"
    const val HI = "hi"
    const val BN = "bn"
    const val ID = "id"
    const val MS = "ms"
    const val RU = "ru"

    val current = mutableStateOf(EN)
    val options = listOf(
        EN to "English",
        HI to "हिन्दी",
        BN to "বাংলা",
        ID to "Bahasa Indonesia",
        MS to "Bahasa Melayu",
        RU to "Русский",
    )

    private var prefs: android.content.SharedPreferences? = null

    fun init(ctx: Context) {
        if (prefs != null) return
        prefs = ctx.getSharedPreferences("lang", Context.MODE_PRIVATE)
        val saved = prefs!!.getString("code", EN) ?: EN
        current.value = if (saved in setOf(HI, BN, ID, MS, RU)) saved else EN
    }

    fun setLang(code: String) {
        val c = if (code in setOf(HI, BN, ID, MS, RU)) code else EN
        current.value = c
        prefs?.edit()?.putString("code", c)?.apply()
    }

    /** Never blank, never throws. */
    fun s(key: String): String {
        when (current.value) {
            HI -> hi[key]?.let { return it }
            BN -> bn[key]?.let { return it }
            ID -> id[key]?.let { return it }
            MS -> ms[key]?.let { return it }
            RU -> ru[key]?.let { return it }
        }
        return en[key] ?: key
    }

    /** Format with args: en/hi value must contain %1$s style placeholders. */
    fun f(key: String, vararg args: Any?): String {
        val base = s(key)
        return try { base.format(*args) } catch (_: Exception) { base }
    }

